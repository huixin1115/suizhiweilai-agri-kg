def _pick(table_crop, table_cat, fallback, crop, category=None):
    """三层取值：按作物 → 按类别 → 兜底。返回 (值, 命中来源)"""
    name = (crop or "").strip()
    if name and name in table_crop:
        return table_crop[name], "crop"
    cat = (category or "").strip()
    if cat and cat in table_cat:
        return table_cat[cat], "category"
    return fallback, "fallback"


def lookup(crop, category=None):
    """
    取某个作物的参考成本。

    返回 dict：{cost_seed: .., ..., "source": "crop|category|fallback", "ref": 命中的键名}
    取不到也一定会返回 FALLBACK 那一份，永远不会是空。
    """
    name = (crop or "").strip()
    if name and name in BY_CROP:
        out = dict(BY_CROP[name])
        out["source"], out["ref"] = "crop", name
        return out

    cat = (category or "").strip()
    if cat and cat in BY_CATEGORY:
        out = dict(BY_CATEGORY[cat])
        out["source"], out["ref"] = "category", cat
        return out

    out = dict(FALLBACK)
    out["source"], out["ref"] = "fallback", "默认"
    return out


def lookup_yield(crop, category=None):
    """取参考亩产（公斤/亩）→ (值, 来源)"""
    return _pick(YIELD_BY_CROP, YIELD_BY_CATEGORY, YIELD_FALLBACK, crop, category)


def lookup_price(crop, category=None):
    """取参考收购价（元/公斤）→ (值, 来源)"""
    return _pick(PRICE_BY_CROP, PRICE_BY_CATEGORY, PRICE_FALLBACK, crop, category)


